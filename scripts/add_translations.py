def main():
    repo_root = Path(__file__).resolve().parent.parent
    targets = [
        repo_root / "knowledge" / "crop_diseases.json",
        repo_root / "backend" / "knowledge" / "crop_diseases.json",
    ]

    for path in targets:
        with open(path, "r", encoding="utf-8") as f:
            data = json.load(f)

        missing = set(data.keys()) - set(TRANSLATIONS.keys())
        if missing:
            raise SystemExit(f"No translations defined for: {missing} in {path}")

        for key, entry in data.items():
            entry["translations"] = TRANSLATIONS[key]

        with open(path, "w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False, indent=2)
            f.write("\n")

        print(f"Updated {path} with translations for {len(data)} entries.")


if __name__ == "__main__":
    main()
